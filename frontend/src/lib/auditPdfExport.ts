// ---------------------------------------------------------------------------
// frontend/src/lib/auditPdfExport.ts
// Generates a professional Audit Technical Specification PDF exactly matching
// the GeM/CPPP reference format (Ref no, Title, Table with 6 columns).
// Uses jsPDF + jsPDF-AutoTable (already installed).
// ---------------------------------------------------------------------------

export interface AuditPdfRow {
  slNo: number
  materialCode: string
  shortDescription: string
  technicalSpecification: string
  unit: string
  quantity: string
}

export interface AuditPdfOptions {
  refNo: string
  title: string
  organization?: string
  date?: string
  rows: AuditPdfRow[]
}

export async function exportAuditReportPdf(opts: AuditPdfOptions): Promise<void> {
  // Dynamic import to avoid bundle bloat
  const { default: jsPDF } = await import('jspdf')
  // @ts-ignore — jspdf-autotable attaches to prototype
  await import('jspdf-autotable')

  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' })

  const pageW = doc.internal.pageSize.getWidth()

  // ── Header ───────────────────────────────────────────────────────────────
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.text(`Ref no ${opts.refNo}`, 14, 16)

  if (opts.organization) {
    doc.setFontSize(9)
    doc.text(opts.organization, pageW - 14, 16, { align: 'right' })
  }

  if (opts.date) {
    doc.setFontSize(9)
    doc.text(`Date: ${opts.date}`, pageW - 14, 21, { align: 'right' })
  }

  // ── Title ─────────────────────────────────────────────────────────────────
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(12)
  doc.text(opts.title, pageW / 2, 30, { align: 'center' })

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  doc.text('TECHNICAL SPECIFICATION', pageW / 2, 38, { align: 'center' })

  // Underline the subtitle
  const textW = doc.getTextWidth('TECHNICAL SPECIFICATION')
  doc.setLineWidth(0.3)
  doc.line(pageW / 2 - textW / 2, 39.5, pageW / 2 + textW / 2, 39.5)

  // ── Table ─────────────────────────────────────────────────────────────────
  const tableData = opts.rows.map(row => [
    String(row.slNo),
    row.materialCode,
    row.shortDescription,
    row.technicalSpecification,
    row.unit,
    row.quantity,
  ])

  ;(doc as any).autoTable({
    startY: 44,
    head: [['Sl.no', 'Material Code', 'Short Description', 'Technical Specification', 'Unit', 'Quantity']],
    body: tableData,
    theme: 'grid',
    styles: {
      font: 'helvetica',
      fontSize: 8,
      cellPadding: { top: 3, right: 3, bottom: 3, left: 3 },
      valign: 'middle',
      overflow: 'linebreak',
      lineColor: [0, 0, 0],
      lineWidth: 0.25,
      textColor: [0, 0, 0],
    },
    headStyles: {
      font: 'helvetica',
      fontStyle: 'bold',
      fontSize: 9,
      fillColor: [255, 255, 255],
      textColor: [0, 0, 0],
      halign: 'center',
      lineColor: [0, 0, 0],
      lineWidth: 0.3,
    },
    columnStyles: {
      0: { cellWidth: 14, halign: 'center' },   // Sl.no
      1: { cellWidth: 32, halign: 'center' },   // Material Code
      2: { cellWidth: 52, halign: 'center' },   // Short Description
      3: { cellWidth: 120, halign: 'left' },    // Technical Specification (widest)
      4: { cellWidth: 16, halign: 'center' },   // Unit
      5: { cellWidth: 22, halign: 'center' },   // Quantity
    },
    alternateRowStyles: { fillColor: [255, 255, 255] },
    margin: { left: 14, right: 14 },
  })

  // ── Footer ────────────────────────────────────────────────────────────────
  const totalPages = (doc as any).internal.getNumberOfPages()
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    doc.setTextColor(120, 120, 120)
    doc.text(
      `BIS Procurement Audit Report  •  Generated by StandardSphere  •  Page ${i} of ${totalPages}`,
      pageW / 2,
      doc.internal.pageSize.getHeight() - 8,
      { align: 'center' }
    )
    doc.setTextColor(0, 0, 0)
  }

  // ── Save ──────────────────────────────────────────────────────────────────
  const safeName = `Audit_Report_${opts.refNo.replace(/[^a-zA-Z0-9]/g, '_')}_${new Date().toISOString().slice(0, 10)}.pdf`
  doc.save(safeName)
}
